// Faction emblems (C-265) from 2D-E's assets/2d/emblems/keys.json: Order's
// Bastion and Chaos's Maw, white with a dark outline, drawn at 16 to 256 px
// on one atlas. This writes src/client/UI/FactionEmblems.luau: the atlas's
// asset id from tools/icons/assets.json `emblems` ({ image, sha256 }; an id
// whose atlas changed since its upload is dropped) and each emblem's name,
// faction, tint and rect per drawn size. Lobby-D reads it too (read-only).
//
// Run from the project root: node tools/icons/emblems.mjs

import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { createHash } from "node:crypto";

const DIR = "assets/2d/emblems";
const keys = JSON.parse(readFileSync(`${DIR}/keys.json`, "utf8"));
const assets = existsSync("tools/icons/assets.json") ? JSON.parse(readFileSync("tools/icons/assets.json", "utf8")) : {};
const up = assets.emblems || {};

const path = `${DIR}/${keys.sheet}`;
if (!existsSync(path)) {
	console.error(`PROBLEM: ${path} is missing`);
	process.exit(1);
}
const sha256 = createHash("sha256").update(readFileSync(path)).digest("hex");
const ok = up.image && up.sha256 === sha256;
const image = ok ? `rbxassetid://${String(up.image).replace(/\D/g, "")}` : "";

const q = (s) => JSON.stringify(s);
const rgb = (hex) => [1, 3, 5].map((i) => parseInt(hex.slice(i, i + 2), 16));
const L = [];
L.push("--!strict");
L.push("-- GENERATED by tools/icons/emblems.mjs from 2D-E's assets/2d/emblems/keys.json");
L.push("-- (C-265); don't edit. Faction emblems, white with a dark outline: tint them");
L.push("-- with ImageColor3 (their faction tint, or white). The image is \"\" until the");
L.push("-- atlas is uploaded. Lobby-D reads this module too.");
L.push("");
L.push("local FactionEmblems = {}");
L.push("");
L.push(`FactionEmblems.image = ${q(image)}`);
L.push(`FactionEmblems.atlasSize = { ${keys.atlasSize.join(", ")} }`);
L.push(`FactionEmblems.sizes = { ${keys.sizes.join(", ")} } -- drawn sizes, pixels`);
L.push("");
L.push("-- key → name, faction, tint { r, g, b } and rect { x, y, w, h } per drawn size");
L.push("FactionEmblems.emblems = {");
for (const [key, e] of Object.entries(keys.tiles)) {
	const rects = keys.sizes.map((s) => `[${s}] = { ${e.rect[s].join(", ")} }`).join(", ");
	L.push(`\t${key} = { name = ${q(e.name)}, faction = ${q(e.faction.toLowerCase())}, tint = { ${rgb(e.tint).join(", ")} }, rect = { ${rects} } },`);
}
L.push("} :: { [string]: { name: string, faction: string, tint: { number }, rect: { [number]: { number } } } }");
L.push("");
L.push("-- The emblem key of `faction` (\"order\" / \"chaos\"), or nil.");
L.push("function FactionEmblems.keyOf(faction: string): string?");
L.push("\tfor key, e in FactionEmblems.emblems do");
L.push("\t\tif e.faction == faction then");
L.push("\t\t\treturn key");
L.push("\t\tend");
L.push("\tend");
L.push("\treturn nil");
L.push("end");
L.push("");
L.push("-- The drawn size to use for a `px`-pixel emblem: the smallest at least as big,");
L.push("-- else the largest.");
L.push("function FactionEmblems.pick(px: number): number");
L.push("\tfor _, s in FactionEmblems.sizes do");
L.push("\t\tif s >= px then");
L.push("\t\t\treturn s");
L.push("\t\tend");
L.push("\tend");
L.push("\treturn FactionEmblems.sizes[#FactionEmblems.sizes]");
L.push("end");
L.push("");
L.push("-- `faction`'s emblem for a `px`-pixel label: image, rect offset, rect size and");
L.push("-- tint; nil before the upload or for an unknown faction.");
L.push("function FactionEmblems.of(faction: string, px: number): (string?, { number }?, { number }?)");
L.push("\tlocal key = FactionEmblems.keyOf(faction)");
L.push("\tif key == nil or FactionEmblems.image == \"\" then");
L.push("\t\treturn nil, nil, nil");
L.push("\tend");
L.push("\tlocal e = FactionEmblems.emblems[key]");
L.push("\treturn FactionEmblems.image, e.rect[FactionEmblems.pick(px)], e.tint");
L.push("end");
L.push("");
L.push("return FactionEmblems");
writeFileSync("src/client/UI/FactionEmblems.luau", L.join("\n") + "\n");
console.log(`${Object.keys(keys.tiles).length} emblems, atlas sha256 ${sha256}, asset id ${image || "(not uploaded)"}${up.image && !ok ? " (STALE: the atlas changed since its upload)" : ""}`);
