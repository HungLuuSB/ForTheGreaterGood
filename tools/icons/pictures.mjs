// Unit pictures (C-262) from 2D-E's assets/2d/pictures/pictures.json (E-11):
// pre-rendered 128-px pictures of each unit in its setting, in its faction's
// own colour (untinted), packed on 1024-px sheets. This writes
// src/client/UI/UnitPictures.luau: each sheet's asset id from
// tools/icons/assets.json `pictures` ([{ image, sha256 }] by sheet; an id
// whose sheet changed since its upload, or with no hash, is dropped) and each
// unit's sheet and rect. A unit without a picture, or on a sheet that isn't
// uploaded, keeps its live portrait (UI/Portrait).
//
// Run from the project root: node tools/icons/pictures.mjs

import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { createHash } from "node:crypto";

const DIR = "assets/2d/pictures";
const pics = JSON.parse(readFileSync(`${DIR}/pictures.json`, "utf8"));
const assets = existsSync("tools/icons/assets.json") ? JSON.parse(readFileSync("tools/icons/assets.json", "utf8")) : {};
const uploaded = assets.pictures || [];

const problems = [];
const sheets = pics.sheets.map((sh, i) => {
	const path = `${DIR}/${sh.file}`;
	if (!existsSync(path)) {
		problems.push(`sheet ${i + 1}: ${path} is missing`);
		return { image: "", stale: false };
	}
	const sha256 = createHash("sha256").update(readFileSync(path)).digest("hex");
	const up = uploaded[i] || {};
	const ok = up.image && up.sha256 === sha256;
	return { image: ok ? `rbxassetid://${String(up.image).replace(/\D/g, "")}` : "", stale: !!up.image && !ok, sha256, size: sh.size };
});
for (const [id, u] of Object.entries(pics.units)) {
	const sh = pics.sheets[u.sheet - 1];
	if (!sh) problems.push(`${id}: sheet ${u.sheet} doesn't exist`);
	else if (u.rect[0] < 0 || u.rect[1] < 0 || u.rect[0] + u.rect[2] > sh.size[0] || u.rect[1] + u.rect[3] > sh.size[1]) problems.push(`${id}: rect ${u.rect} off sheet ${u.sheet}`);
}
if (problems.length > 0) {
	for (const p of problems) console.error(`PROBLEM: ${p}`);
	process.exit(1);
}

const q = (s) => JSON.stringify(s);
const L = [];
L.push("--!strict");
L.push("-- GENERATED by tools/icons/pictures.mjs from 2D-E's assets/2d/pictures/pictures.json");
L.push("-- (C-262); don't edit. Pre-rendered unit pictures in their faction's colour,");
L.push("-- untinted. A sheet's id is \"\" until it's uploaded; its units keep their live");
L.push("-- portrait until then.");
L.push("");
L.push("local UnitPictures = {}");
L.push("");
L.push(`UnitPictures.TILE = ${pics.tile} -- pixels per picture`);
L.push("");
L.push("-- one image per sheet");
L.push("UnitPictures.sheets = {");
for (const sh of sheets) L.push(`\t${q(sh.image)},`);
L.push("} :: { string }");
L.push("");
L.push("-- def id → { sheet, x, y }: its picture's sheet and top-left pixel");
L.push("UnitPictures.units = {");
for (const id of Object.keys(pics.units).sort()) {
	const u = pics.units[id];
	L.push(`\t${id} = { ${u.sheet}, ${u.rect[0]}, ${u.rect[1]} },`);
}
L.push("} :: { [string]: { number } }");
L.push("");
L.push("-- A def's picture: its sheet's image and top-left pixel, or nil (no picture,");
L.push("-- or its sheet isn't uploaded yet).");
L.push("function UnitPictures.of(defId: string): (string?, number, number)");
L.push("\tlocal u = UnitPictures.units[defId]");
L.push("\tlocal image = u and UnitPictures.sheets[u[1]]");
L.push("\tif u == nil or image == nil or image == \"\" then");
L.push("\t\treturn nil, 0, 0");
L.push("\tend");
L.push("\treturn image, u[2], u[3]");
L.push("end");
L.push("");
L.push("return UnitPictures");
writeFileSync("src/client/UI/UnitPictures.luau", L.join("\n") + "\n");

const live = Object.entries(pics.units).filter(([, u]) => sheets[u.sheet - 1] && sheets[u.sheet - 1].image).length;
console.log(`${Object.keys(pics.units).length} unit pictures on ${sheets.length} sheet(s); ${live} with an uploaded sheet; ${(pics.missing || []).length} defs listed as missing (live portrait)`);
sheets.forEach((sh, i) => console.log(`sheet ${i + 1}: ${pics.sheets[i].file}, sha256 ${sh.sha256}, asset id ${sh.image || "(none: upload it, then add { image, sha256 } to tools/icons/assets.json `pictures`)"}${sh.stale ? " (WARNING: changed since its upload)" : ""}`));
