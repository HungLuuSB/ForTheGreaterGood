// The UI icon atlas (C-259) from 2D-E's assets/2d/ui/: resource and stat
// icons (supply, power, build time, wind, tidal, health, DPS, range, ...),
// white with a dark edge, tinted in code with ImageColor3. keys.json gives
// each key's name, group, suggested tint and its rect on the atlas at 16, 24
// and 32 px. This writes src/client/UI/UiIcons.luau, pure data the lobby can
// require too (lobby-D's Codex), with the atlas's asset id from
// tools/icons/assets.json `ui`: { image, sha256 }. An id whose atlas changed
// since its upload (or with no hash) is dropped, so a stale image is never
// shipped; until there's an id the UI keeps its text marks.
//
// Run from the project root: node tools/icons/ui_icons.mjs

import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { createHash } from "node:crypto";

const DIR = "assets/2d/ui";
const keys = JSON.parse(readFileSync(`${DIR}/keys.json`, "utf8"));
const atlas = `${DIR}/${keys.sheet}`;
const sha256 = createHash("sha256").update(readFileSync(atlas)).digest("hex");

const assets = existsSync("tools/icons/assets.json") ? JSON.parse(readFileSync("tools/icons/assets.json", "utf8")) : {};
const ui = assets.ui || {};
const stale = ui.image && ui.sha256 !== sha256;
const image = ui.image && !stale ? `rbxassetid://${String(ui.image).replace(/\D/g, "")}` : "";

const problems = [];
const sizes = keys.sizes;
for (const [key, t] of Object.entries(keys.tiles)) {
	if (!/^[a-z][A-Za-z]*$/.test(key)) problems.push(`${key}: not a plain identifier`);
	if (!/^#[0-9A-Fa-f]{6}$/.test(t.tint || "")) problems.push(`${key}: tint ${t.tint}`);
	for (const s of sizes) {
		const r = t.rect && t.rect[s];
		if (!r || r.length !== 4) problems.push(`${key}: no ${s}-px rect`);
		else if (r[0] < 0 || r[1] < 0 || r[0] + r[2] > keys.atlasSize[0] || r[1] + r[3] > keys.atlasSize[1]) problems.push(`${key}: ${s}-px rect ${r} off the atlas`);
	}
}
if (problems.length > 0) {
	for (const p of problems) console.error(`PROBLEM: ${p}`);
	process.exit(1);
}

const q = (s) => JSON.stringify(s);
const rgb = (hex) => [1, 3, 5].map((i) => parseInt(hex.slice(i, i + 2), 16)).join(", ");
const L = [];
L.push("--!strict");
L.push("-- GENERATED by tools/icons/ui_icons.mjs from 2D-E's assets/2d/ui/keys.json (C-259);");
L.push("-- don't edit. Resource and stat icons on one atlas, white with a dark edge,");
L.push("-- tinted by ImageColor3. The atlas's asset id comes from tools/icons/assets.json");
L.push("-- `ui` (\"\" until uploaded: the UI keeps its text marks). Pure data: the lobby");
L.push("-- requires it too.");
L.push("");
L.push("local UiIcons = {}");
L.push("");
L.push("export type Icon = { name: string, group: string, tint: { number }, rect: { [number]: { number } } }");
L.push("");
L.push(`UiIcons.image = ${q(image)}`);
L.push(`UiIcons.sizes = { ${sizes.join(", ")} } :: { number } -- pixels; a rect per size`);
L.push("");
L.push("-- key → name, group, suggested tint (r, g, b) and its rect per size: { x, y, w, h }");
L.push("UiIcons.icons = {");
for (const [key, t] of Object.entries(keys.tiles)) {
	const rects = sizes.map((s) => `[${s}] = { ${t.rect[s].join(", ")} }`).join(", ");
	L.push(`\t${key} = { name = ${q(t.name)}, group = ${q(t.group)}, tint = { ${rgb(t.tint)} }, rect = { ${rects} } },`);
}
L.push("} :: { [string]: Icon }");
L.push("");
L.push("return UiIcons");
writeFileSync("src/client/UI/UiIcons.luau", L.join("\n") + "\n");

console.log(`${Object.keys(keys.tiles).length} UI icons at ${sizes.join(", ")} px from ${atlas} (${keys.atlasSize.join(" x ")}), sha256 ${sha256}`);
if (stale) console.log("WARNING: the atlas changed since its upload: its asset id is dropped until it's uploaded again");
console.log(`asset id ${image || "(none: upload the atlas, then add { image, sha256 } as `ui` to tools/icons/assets.json)"}`);
